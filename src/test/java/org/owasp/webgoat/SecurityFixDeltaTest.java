  @Nested
  @DisplayName("Assignment5 SQL injection protection tests")
  class Assignment5DeltaTests {

    @Test
    @DisplayName("Login must not be bypassed by SQL injection payload due to parameterized query")
    void loginIsNotBypassedBySqlInjectionPayload() throws Exception {
      // Arrange
      LessonDataSource dataSource = Mockito.mock(LessonDataSource.class);
      Flags flags = Mockito.mock(Flags.class);

      Connection connection = Mockito.mock(Connection.class);
      PreparedStatement preparedStatement = Mockito.mock(PreparedStatement.class);
      ResultSet resultSet = Mockito.mock(ResultSet.class);

      Mockito.when(dataSource.getConnection()).thenReturn(connection);
      Mockito.when(connection.prepareStatement(Mockito.anyString())).thenReturn(preparedStatement);
      // Simulate that query returns no rows even with injection payload
      Mockito.when(preparedStatement.executeQuery()).thenReturn(resultSet);
      Mockito.when(resultSet.next()).thenReturn(false);

      Assignment5 assignment5 = new Assignment5(dataSource, flags);

      // Injection-like payload that would previously have broken out of the quotes:
      String username = "Larry' OR '1'='1";
      String password = "anything' OR '1'='1";

      // Act
      AttackResult result = assignment5.login(username, password);

      // Assert
      // Should be treated as literal parameter values, not as executable SQL, so login must fail
      assertThat(result)
          .as("Injection payload must not bypass authentication")
          .matches(r -> !r.getLessonCompleted());

      // Additionally verify that PreparedStatement parameters are bound as parameters,
      // not concatenated directly into the SQL string.
      ArgumentCaptor<String> sqlCaptor = ArgumentCaptor.forClass(String.class);
      Mockito.verify(connection).prepareStatement(sqlCaptor.capture());
      String usedSql = sqlCaptor.getValue();
      assertThat(usedSql)
          .as("SQL should use parameter placeholders, not inline user input")
          .contains("userid = ?")
          .contains("password = ?")
          .doesNotContain(username)
          .doesNotContain(password);

      Mockito.verify(preparedStatement).setString(1, username);
      Mockito.verify(preparedStatement).setString(2, password);
    }

    @Test
    @DisplayName("Successful login still works with correct, non-injection credentials")
    void loginSucceedsForValidUser() throws Exception {
      // Arrange
      LessonDataSource dataSource = Mockito.mock(LessonDataSource.class);
      Flags flags = Mockito.mock(Flags.class);

      Connection connection = Mockito.mock(Connection.class);
      PreparedStatement preparedStatement = Mockito.mock(PreparedStatement.class);
      ResultSet resultSet = Mockito.mock(ResultSet.class);

      Mockito.when(dataSource.getConnection()).thenReturn(connection);
      Mockito.when(connection.prepareStatement(Mockito.anyString())).thenReturn(preparedStatement);
      Mockito.when(preparedStatement.executeQuery()).thenReturn(resultSet);
      Mockito.when(resultSet.next()).thenReturn(true);
      Mockito.when(flags.getFlag(5)).thenReturn("FLAG-5");

      Assignment5 assignment5 = new Assignment5(dataSource, flags);

      // Act
      AttackResult result = assignment5.login("Larry", "correct-password");

      // Assert
      assertThat(result)
          .as("Legitimate login should still succeed with parameterized query")
          .matches(AttackResult::getLessonCompleted);
      Mockito.verify(preparedStatement).setString(1, "Larry");
      Mockito.verify(preparedStatement).setString(2, "correct-password");
    }
  }

