  @Nested
  @DisplayName("InsecureDeserializationTask whitelist-based deserialization tests")
  class InsecureDeserializationTaskDeltaTests {

    @Test
    @DisplayName("Malicious class outside whitelist must be rejected on deserialization")
    void deserializationOfNonWhitelistedClassIsRejected() throws Exception {
      // Arrange
      InsecureDeserializationTask task = new InsecureDeserializationTask();

      // Create a serialized payload of a non-whitelisted type (e.g., StringBuilder)
      StringBuilder maliciousObject = new StringBuilder("malicious");
      byte[] serialized;
      try (ByteArrayOutputStream baos = new ByteArrayOutputStream();
           ObjectOutputStream oos = new ObjectOutputStream(baos)) {
        oos.writeObject(maliciousObject);
        oos.flush();
        serialized = baos.toByteArray();
      }

      // Encode to base64 and apply the same URL-safe substitutions as production code expects
      String b64 = java.util.Base64.getEncoder().encodeToString(serialized)
          .replace('+', '-')
          .replace('/', '_');

      // Act
      AttackResult result = task.completed(b64);

      // Assert
      // The filter should reject the class (not in whitelist), leading to a failure result.
      assertThat(result)
          .as("Deserialization of non-whitelisted class should fail")
          .matches(r -> !r.getLessonCompleted());
    }

    @Test
    @DisplayName("Whitelisted VulnerableTaskHolder can still be deserialized successfully (behavior preserved)")
    void whitelistedClassIsStillAccepted() throws Exception {
      // Arrange
      InsecureDeserializationTask task = new InsecureDeserializationTask();

      VulnerableTaskHolder holder = new VulnerableTaskHolder("task", 1000L);
      byte[] serialized;
      try (ByteArrayOutputStream baos = new ByteArrayOutputStream();
           ObjectOutputStream oos = new ObjectOutputStream(baos)) {
        oos.writeObject(holder);
        oos.flush();
        serialized = baos.toByteArray();
      }

      String b64 = java.util.Base64.getEncoder().encodeToString(serialized)
          .replace('+', '-')
          .replace('/', '_');

      // Act
      AttackResult result = task.completed(b64);

      // Assert
      // We cannot easily control the internal timing logic, but for a valid, whitelisted object
      // the flow should at least not throw and may succeed or fail based on timing window.
      // Here we assert it does not blow up and is not misclassified as a class-type failure.
      assertThat(result)
          .as("Whitelisted class should pass class-based filter and be processed")
          .isNotNull();
    }

    @Test
    @DisplayName("Invalid base64 or corrupted tokens should not lead to successful completion")
    void invalidTokensDoNotSucceed() {
      // Arrange
      InsecureDeserializationTask task = new InsecureDeserializationTask();
      String invalid = "!!!not-a-valid-token!!!";

      // Act / Assert
      assertThrows(
          Exception.class,
          () -> {
            // completed() declares IOException, but filter or decoding can throw runtime exceptions as well.
            AttackResult result = task.completed(invalid);
            // Additional safety: we still assert that no success is reported if it unexpectedly returns.
            assertThat(result)
                .as("Invalid token must never result in a successful lesson completion")
                .matches(r -> r == null || !r.getLessonCompleted());
          });
    }
  }
