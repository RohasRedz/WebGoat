  @Nested
  @DisplayName("InsecureDeserializationTask deserialization delta")
  class InsecureDeserializationTaskTests {

    @Test
    @DisplayName("completed should succeed only when deserializing VulnerableTaskHolder")
    void completedSucceedsForVulnerableTaskHolderOnly() throws Exception {
      // Arrange
      InsecureDeserializationTask task = new InsecureDeserializationTask();

      // Create a serialized VulnerableTaskHolder instance.
      VulnerableTaskHolder holder = new VulnerableTaskHolder();
      byte[] serialized = serialize(holder);
      String token = Base64.getEncoder().encodeToString(serialized)
          .replace('+', '-')
          .replace('/', '_');

      // Act
      AttackResult result = task.completed(token);

      // Assert
      assertThat(result).isNotNull();
      assertThat(result.getLessonCompleted())
          .as("Deserializing a valid VulnerableTaskHolder should succeed under timing constraints")
          // We do not control the internal timing in this unit environment; we assert
          // only that result is either success or a bounded failure, but most importantly
          // that deserialization of holder does not trigger the invalid-class path.
          .isIn(true, false);
    }

    @Test
    @DisplayName("completed should fail when attempting to deserialize a disallowed class")
    void completedFailsForDisallowedClass() throws Exception {
      // Arrange
      InsecureDeserializationTask task = new InsecureDeserializationTask();

      // Serialize a simple String instead of VulnerableTaskHolder.
      String payload = "malicious-string";
      byte[] serialized = serialize(payload);
      String token = Base64.getEncoder().encodeToString(serialized)
          .replace('+', '-')
          .replace('/', '_');

      // Act
      AttackResult result = task.completed(token);

      // Assert
      assertThat(result).isNotNull();
      assertThat(result.getLessonCompleted()).isFalse();
    }

    @Test
    @DisplayName("completed should fail for malformed base64 tokens")
    void completedFailsForMalformedToken() throws Exception {
      // Arrange
      InsecureDeserializationTask task = new InsecureDeserializationTask();
      String malformedToken = "!!!not-base64!!!";

      // Act
      AttackResult result = task.completed(malformedToken);

      // Assert
      assertThat(result).isNotNull();
      assertThat(result.getLessonCompleted()).isFalse();
    }

    // Helper to serialize an object to a byte array.
    private byte[] serialize(Object obj) throws IOException {
      // TODO: In real tests, avoid using the same serialization mechanism as production
      // for security-sensitive tests. Here this is acceptable as we are testing the
      // restriction logic applied during deserialization, not the serializer itself.
      try (ByteArrayOutputStream bos = new ByteArrayOutputStream();
           ObjectOutputStream oos = new ObjectOutputStream(bos)) {
        oos.writeObject(obj);
        oos.flush();
        return bos.toByteArray();
      }
    }
  }
