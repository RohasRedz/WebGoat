  // batch-2: Assignment5 – SQL Injection fix (parameterized query)
  // ---------------------------------------------------------------------------

  @Nested
  @DisplayName("Assignment5 SQL injection delta")
  class Assignment5Tests {

    @Test
    @DisplayName("login should use a parameterized PreparedStatement (no concatenation)")
    void loginUsesParameterizedPreparedStatement() throws Exception {
      // Arrange
      LessonDataSource dataSource = mock(LessonDataSource.class);
      Connection connection = mock(Connection.class);
      PreparedStatement preparedStatement = mock(PreparedStatement.class);
      ResultSet resultSet = mock(ResultSet.class);
      Flags flags = mock(Flags.class);

      when(dataSource.getConnection()).thenReturn(connection);
      when(connection.prepareStatement(anyString())).thenReturn(preparedStatement);
      when(preparedStatement.executeQuery()).thenReturn(resultSet);
      when(resultSet.next()).thenReturn(true);
      when(flags.getFlag(5)).thenReturn("FLAG-5");

      Assignment5 assignment5 = new Assignment5(dataSource, flags);

      String username = "Larry";
      String password = "safePassword";

      // Act
      AttackResult result = assignment5.login(username, password);

      // Assert
      // Verify that the SQL string uses placeholders rather than concatenation.
      ArgumentCaptor<String> sqlCaptor = ArgumentCaptor.forClass(String.class);
      verify(connection).prepareStatement(sqlCaptor.capture());
      String sqlUsed = sqlCaptor.getValue();

      assertThat(sqlUsed)
          .as("SQL should contain parameter placeholders and not raw user input")
          .contains("userid = ?")
          .contains("password = ?")
          .doesNotContain(username)
          .doesNotContain(password);

      // And verify that parameters are bound via setString in the correct order.
      verify(preparedStatement).setString(1, username);
      verify(preparedStatement).setString(2, password);

      // Additionally validate that, with correct credentials, login succeeds.
      assertThat(result).isNotNull();
      assertThat(result.getLessonCompleted()).isTrue();
    }

    @Test
    @DisplayName("login should fail for invalid credentials even with prepared statement")
    void loginFailsForInvalidCredentialsWithPreparedStatement() throws Exception {
      // Arrange
      LessonDataSource dataSource = mock(LessonDataSource.class);
      Connection connection = mock(Connection.class);
      PreparedStatement preparedStatement = mock(PreparedStatement.class);
      ResultSet resultSet = mock(ResultSet.class);
      Flags flags = mock(Flags.class);

      when(dataSource.getConnection()).thenReturn(connection);
      when(connection.prepareStatement(anyString())).thenReturn(preparedStatement);
      when(preparedStatement.executeQuery()).thenReturn(resultSet);
      // No rows found
      when(resultSet.next()).thenReturn(false);

      Assignment5 assignment5 = new Assignment5(dataSource, flags);

      String username = "Larry";
      String password = "wrongPassword";

      // Act
      AttackResult result = assignment5.login(username, password);

      // Assert
      assertThat(result).isNotNull();
      assertThat(result.getLessonCompleted()).isFalse();
      // Ensure query was still parameterized:
      verify(preparedStatement).setString(1, username);
      verify(preparedStatement).setString(2, password);
    }

    @Test
    @DisplayName("login should reject non-Larry users before hitting the database")
    void loginRejectsNonLarryBeforeDatabase() throws Exception {
      // Arrange
      LessonDataSource dataSource = mock(LessonDataSource.class);
      Flags flags = mock(Flags.class);
      Assignment5 assignment5 = new Assignment5(dataSource, flags);

      // Act
      AttackResult result = assignment5.login("Alice", "whatever");

      // Assert
      assertThat(result).isNotNull();
      assertThat(result.getLessonCompleted()).isFalse();
      // DB should never be touched for non-Larry user
      verifyNoInteractions(dataSource);
    }
  }

